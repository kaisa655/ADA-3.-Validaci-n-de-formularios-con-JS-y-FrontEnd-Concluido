CREATE TABLE IF NOT EXISTS usuarios (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 nombre VARCHAR(80) NOT NULL,
 correo VARCHAR(190) NOT NULL UNIQUE,
 contrasena VARCHAR(255) NOT NULL,
 fecha_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS juegos (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 usuario_id INT UNSIGNED NOT NULL,
 titulo VARCHAR(120) NOT NULL,
 descripcion TEXT NOT NULL,
 categoria VARCHAR(50) NOT NULL,
 url_juego VARCHAR(2048) DEFAULT NULL,
 portada VARCHAR(255) DEFAULT NULL,
 fecha_publicacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_juegos_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE,
 INDEX idx_juegos_fecha (fecha_publicacion),
 INDEX idx_juegos_categoria (categoria)
) ENGINE=InnoDB;
